"""结算失败代码与安全原因摘要。"""
SETTLEMENT_FAILURE_CODE_THEORETICAL = "THEORETICAL_NOT_ZERO_SUM"
SETTLEMENT_FAILURE_CODE_CONTRACT = "SETTLEMENT_CONTRACT_INVALID"
SETTLEMENT_FAILURE_CODE_VALIDATION = "SETTLEMENT_VALIDATION_FAILED"
SETTLEMENT_FAILURE_CODE_INFRASTRUCTURE = "SETTLEMENT_INFRASTRUCTURE_FAILURE"
SETTLEMENT_FAILURE_REASON_LIMIT = 500
SETTLEMENT_FAILURE_CODE_LIMIT = 64



def limit_settlement_failure_reason(reason: str) -> str:
    """规范化失败摘要为单行并限制持久化长度。"""
    normalized = " ".join(str(reason or "").strip().split())
    return normalized[:SETTLEMENT_FAILURE_REASON_LIMIT] or "结算执行失败"
